#!/usr/bin/env python3
"""Regenerate results/summary/comparison.md from the raw JSON in results/raw.

Every number in the report comes from here, so the write-up cannot drift from
the measurements. Run after any re-benchmark:

    python3 src/summarize.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "results", "raw")
OUT = os.path.join(ROOT, "results", "summary", "comparison.md")

NEW, OLD = "3.8", "3.6"


def load(name):
    with open(os.path.join(RAW, name)) as f:
        return json.load(f)


def main():
    easy = {NEW: load("bench-3.8.json"), OLD: load("bench-3.6.json")}
    hard = {NEW: load("hard-3.8.json"), OLD: load("hard-3.6.json")}
    retest = load("retest-3.6.json")

    L = []
    L.append("# Qwen3.8-27B vs Qwen3.6-27B — measured comparison\n")
    L.append(
        "_Generated by `src/summarize.py` from `results/raw/`. Do not edit by hand._\n"
    )

    # ---- headline ----
    tot = {}
    for k in (NEW, OLD):
        c = easy[k]["summary"]["correct"] + hard[k]["summary"]["correct"]
        n = easy[k]["summary"]["total_tasks"] + hard[k]["summary"]["total_tasks"]
        tk = (
            easy[k]["summary"]["total_completion_tokens"]
            + hard[k]["summary"]["total_completion_tokens"]
        )
        w = easy[k]["summary"]["bench_wall_s"] + hard[k]["summary"]["bench_wall_s"]
        tot[k] = {"correct": c, "n": n, "tokens": tk, "wall": w}

    L.append("## Headline\n")
    L.append("| Metric | Qwen3.8 | Qwen3.6 | Delta |")
    L.append("|---|---:|---:|---:|")
    L.append(
        "| Accuracy | {}/{} ({:.1f}%) | {}/{} ({:.1f}%) | +{} tasks |".format(
            tot[NEW]["correct"],
            tot[NEW]["n"],
            100 * tot[NEW]["correct"] / tot[NEW]["n"],
            tot[OLD]["correct"],
            tot[OLD]["n"],
            100 * tot[OLD]["correct"] / tot[OLD]["n"],
            tot[NEW]["correct"] - tot[OLD]["correct"],
        )
    )
    L.append(
        "| Completion tokens | {:,} | {:,} | {:.2f}x fewer |".format(
            tot[NEW]["tokens"],
            tot[OLD]["tokens"],
            tot[OLD]["tokens"] / tot[NEW]["tokens"],
        )
    )
    L.append(
        "| Wall clock | {:,.0f}s | {:,.0f}s | {:.2f}x faster |".format(
            tot[NEW]["wall"], tot[OLD]["wall"], tot[OLD]["wall"] / tot[NEW]["wall"]
        )
    )
    L.append("")

    # ---- per suite ----
    L.append("## Per suite\n")
    L.append("| Suite | Tasks | 3.8 correct | 3.6 correct | 3.8 tokens | 3.6 tokens |")
    L.append("|---|---:|---:|---:|---:|---:|")
    for label, d in (("Baseline", easy), ("Hard", hard)):
        s8, s6 = d[NEW]["summary"], d[OLD]["summary"]
        L.append(
            "| {} | {} | {} ({}%) | {} ({}%) | {:,} | {:,} |".format(
                label,
                s8["total_tasks"],
                s8["correct"],
                s8["accuracy_pct"],
                s6["correct"],
                s6["accuracy_pct"],
                s8["total_completion_tokens"],
                s6["total_completion_tokens"],
            )
        )
    L.append("")

    # ---- categories ----
    L.append("## Hard suite by category\n")
    L.append("| Category | Qwen3.8 | Qwen3.6 |")
    L.append("|---|---:|---:|")
    for cat in hard[NEW]["summary"]["by_category"]:
        L.append(
            "| {} | {} | {} |".format(
                cat,
                hard[NEW]["summary"]["by_category"][cat],
                hard[OLD]["summary"]["by_category"].get(cat, "-"),
            )
        )
    L.append("")

    # ---- throughput ----
    L.append("## Throughput (median of 3)\n")
    L.append(
        "| Case | Prompt tokens | 3.8 gen t/s | 3.6 gen t/s | 3.8 prefill t/s | 3.6 prefill t/s |"
    )
    L.append("|---|---:|---:|---:|---:|---:|")
    for p8, p6 in zip(easy[NEW]["perf"], easy[OLD]["perf"]):
        m8, m6 = p8["median"], p6["median"]
        L.append(
            "| {} | {:,} | {:.2f} | {:.2f} | {:,.2f} | {:,.2f} |".format(
                p8["case"],
                m8["prompt_n"],
                m8["gen_tok_s"],
                m6["gen_tok_s"],
                m8["prompt_tok_s"],
                m6["prompt_tok_s"],
            )
        )
    L.append("")

    # ---- failures ----
    L.append("## Every failure\n")
    L.append("| Task | Suite | Model | Category | Tokens | Wall | What happened |")
    L.append("|---|---|---|---|---:|---:|---|")
    rows = []
    for suite_name, d in (("baseline", easy), ("hard", hard)):
        for k in (NEW, OLD):
            items = d[k].get("quality") or d[k].get("results") or []
            for r in items:
                if not r.get("correct"):
                    what = (
                        r.get("note")
                        or r.get("error")
                        or ("answered %r" % (r.get("answer") or "")[:40])
                    )
                    rows.append(
                        "| {} | {} | {} | {} | {} | {}s | {} |".format(
                            r["id"],
                            suite_name,
                            k,
                            r.get("category", "-"),
                            r.get("completion_tokens"),
                            r.get("wall_s"),
                            what,
                        )
                    )
    L.extend(rows if rows else ["| _none_ | | | | | | |"])
    L.append("")

    # ---- retest ----
    L.append("## Budget re-test (3.6 only, cap raised 8,192 -> 32,768)\n")
    L.append("Confirms the two code failures are not an artefact of the token cap.\n")
    L.append("| Task | Correct | Tokens | finish_reason | Wall | Note |")
    L.append("|---|---|---:|---|---:|---|")
    for tid, r in sorted(retest.items()):
        L.append(
            "| {} | {} | {} | {} | {}s | {} |".format(
                tid,
                r.get("correct"),
                r.get("completion_tokens"),
                r.get("finish"),
                r.get("wall_s"),
                r.get("note", "-"),
            )
        )
    L.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
